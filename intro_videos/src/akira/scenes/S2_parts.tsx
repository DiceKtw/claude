export const FACE: Cub[] = smoothCubs(FACE_PTS, 1);
export const HAIR: Cub[] = smoothCubs(HAIR_PTS, 1);
export const BANG: Cub[] = smoothCubs(BANG_PTS, 1);

const revCub = ([a, b, c, d]: Cub): Cub => [d, c, b, a];

const r1 = (v: number) => Math.round(v * 10) / 10;
const cubsTail = (cs: Cub[]) => cs.map(([, b, c, d]) => `C ${r1(b[0])} ${r1(b[1])} ${r1(c[0])} ${r1(c[1])} ${r1(d[0])} ${r1(d[1])}`).join(' ');

/** 髮型區塊的填色路徑：外輪廓（收在太陽穴）→ 接到瀏海尾端 → 沿瀏海反走回根部 → 封閉 */
export const HAIR_FILL_D = (() => {
	const back = BANG.slice().reverse().map(revCub);
	const [bx, by] = back[0][0];
	return `${cubsD(HAIR)} L ${r1(bx)} ${r1(by)} ${cubsTail(back)} Z`;
})();

